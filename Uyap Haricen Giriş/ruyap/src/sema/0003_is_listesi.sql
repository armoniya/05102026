-- Büro veritabanı — İş Listesi (yeni model, 15.11.2026).
-- Buluttaki zs_* tablolarının yerini alır; işler icra şemasındaki dosya/taraf/evrak/tebligat
-- satırlarına yabancı anahtarla bağlanır ("icra ile İş Listesi ortak hareket eder").
-- Elle yazılır (icra şeması gibi Django'dan üretilmez). Uygulanmış hâli değiştirilmez.

-- Büro kullanıcıları: buluttaki hesaplardan yalnız ad ve rol eşitlenir.
CREATE TABLE kullanici (
    id          bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hesap_adi   varchar(150) NOT NULL UNIQUE,
    ad          varchar(200) NOT NULL DEFAULT '',
    rol         varchar(10)  NOT NULL DEFAULT 'uye' CHECK (rol IN ('yonetici', 'uye')),
    aktif       boolean      NOT NULL DEFAULT true,
    olusturulma timestamptz  NOT NULL DEFAULT now(),
    guncelleme  timestamptz  NOT NULL DEFAULT now()
);

-- Süreçler (ör. "Tebligat → Kesinleştirme") ve sıralı aşamaları.
CREATE TABLE surec (
    id          bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    anahtar     varchar(60)  NOT NULL UNIQUE,
    ad          varchar(200) NOT NULL,
    aciklama    text         NOT NULL DEFAULT '',
    dosya_turu  varchar(20)  NOT NULL DEFAULT '',
    hazir       boolean      NOT NULL DEFAULT false,
    aktif       boolean      NOT NULL DEFAULT true,
    olusturulma timestamptz  NOT NULL DEFAULT now()
);

CREATE TABLE surec_asama (
    id       bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    surec_id bigint       NOT NULL REFERENCES surec(id) ON DELETE CASCADE,
    anahtar  varchar(60)  NOT NULL,
    ad       varchar(200) NOT NULL,
    sira     integer      NOT NULL DEFAULT 0,
    -- İcra durum olayıyla eşleşme (ör. 'tebligat_durumu:teblig'); boşsa elle.
    olay_turu varchar(60) NOT NULL DEFAULT '',
    CONSTRAINT uq_surec_asama UNIQUE (surec_id, anahtar)
);

CREATE TABLE etiket (
    id          bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    anahtar     varchar(60)  NULL UNIQUE,  -- hazır/taşınan etiketin eski anahtarı ('e-icra' gibi)
    ad          varchar(100) NOT NULL,
    renk       varchar(20)  NOT NULL DEFAULT '',
    ust_id      bigint       NULL REFERENCES etiket(id) ON DELETE SET NULL,
    -- NULL: büro geneli; dolu: kişiye özel etiket.
    sahip_id    bigint       NULL REFERENCES kullanici(id) ON DELETE CASCADE,
    olusturulma timestamptz  NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX uq_etiket_ad ON etiket (coalesce(sahip_id, 0), lower(ad));

-- İş şablonları. Süre "gün sayısı" değil, türüyle tanımlanır (B-8):
--   takvim_gunu  : sure_deger gün sonra
--   is_gunu      : sure_deger iş günü sonra (hafta sonu + resmî tatil atlanır)
--   ayin_gunu    : sonraki ayın/bu ayın sure_deger. günü (geçtiyse sonraki ay; iş gününe kayar)
--   tarih_sor    : tarih kullanıcıya sorulur (öneri yok)
CREATE TABLE sablon (
    id             bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    anahtar        varchar(60)  NULL UNIQUE,  -- hazır şablonlar ve taşınanlar için kararlı kimlik
    baslik         varchar(300) NOT NULL,
    aciklama       text         NOT NULL DEFAULT '',
    kontrol        text         NOT NULL DEFAULT '',  -- işi kapatırken sorulan soru
    tur            varchar(10)  NOT NULL DEFAULT 'is',
    onay_gerekir   boolean      NOT NULL DEFAULT false,
    oncelik        smallint     NOT NULL DEFAULT 1 CHECK (oncelik BETWEEN 0 AND 2),
    sure_turu      varchar(12)  NOT NULL DEFAULT 'is_gunu'
                   CHECK (sure_turu IN ('takvim_gunu', 'is_gunu', 'ayin_gunu', 'tarih_sor')),
    sure_deger     integer      NOT NULL DEFAULT 1 CHECK (sure_deger >= 0),
    taraf          varchar(20)  NOT NULL DEFAULT '',   -- 'borclu' vb.: iş taraf seçtirir
    eylem          varchar(60)  NOT NULL DEFAULT '',   -- ör. 'ekran:evrak', 'ptt:barkod'
    evrak_deseni   varchar(300) NOT NULL DEFAULT '',   -- belge adı eşleşmesi (B-6)
    olay_turu      varchar(60)  NOT NULL DEFAULT '',   -- icra durum olayından iş açma (L7)
    surec_asama_id bigint       NULL REFERENCES surec_asama(id) ON DELETE SET NULL,
    eski_adlar     text[]       NOT NULL DEFAULT '{}',
    hazir          boolean      NOT NULL DEFAULT false,
    aktif          boolean      NOT NULL DEFAULT true,
    olusturan_id   bigint       NULL REFERENCES kullanici(id) ON DELETE SET NULL,
    olusturulma    timestamptz  NOT NULL DEFAULT now(),
    guncelleme     timestamptz  NOT NULL DEFAULT now()
);

CREATE TABLE sablon_etiket (
    sablon_id bigint NOT NULL REFERENCES sablon(id) ON DELETE CASCADE,
    etiket_id bigint NOT NULL REFERENCES etiket(id) ON DELETE CASCADE,
    PRIMARY KEY (sablon_id, etiket_id)
);

-- İş silsilesi: şablon + sonuç → sonraki şablon (varsayılan değerlerle, B-6/7/19).
-- sonraki_sablon_id NULL ise aynı şablon yinelenir (ör. "henüz dönmedi → 2 gün sonra tekrar").
CREATE TABLE sablon_sonraki (
    id                bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sablon_id         bigint       NOT NULL REFERENCES sablon(id) ON DELETE CASCADE,
    sonuc             varchar(10)  NOT NULL CHECK (sonuc IN ('olumlu', 'olumsuz', 'bekliyor')),
    sonraki_sablon_id bigint       NULL REFERENCES sablon(id) ON DELETE CASCADE,
    sonuc_adi         varchar(120) NOT NULL DEFAULT '',  -- düğmede görünen ad ("Tebliğ edildi")
    sure_turu         varchar(12)  NULL
                      CHECK (sure_turu IN ('takvim_gunu', 'is_gunu', 'ayin_gunu', 'tarih_sor')),
    sure_deger        integer      NULL CHECK (sure_deger >= 0),
    CONSTRAINT uq_sablon_sonraki UNIQUE (sablon_id, sonuc)
);

-- Tekrar eden işler / rutinler (B-10, B-11). Her kuralın en çok bir açık örneği olur.
CREATE TABLE tekrar_kurali (
    id           bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    baslik       varchar(300) NOT NULL,
    aciklama     text         NOT NULL DEFAULT '',
    sablon_id    bigint       NULL REFERENCES sablon(id) ON DELETE SET NULL,
    sorumlu_id   bigint       NOT NULL REFERENCES kullanici(id) ON DELETE CASCADE,
    olusturan_id bigint       NULL REFERENCES kullanici(id) ON DELETE SET NULL,
    kural        varchar(16)  NOT NULL
                 CHECK (kural IN ('gunluk', 'is_gunu', 'haftalik', 'aylik', 'ay_basi_is_gunu')),
    -- haftalik: ISO gün numaraları (1=Pzt … 7=Paz); aylik: ayın günü (1–31, ay kısaysa son gün)
    haftanin_gunleri smallint[] NOT NULL DEFAULT '{}',
    ayin_gunu    smallint     NULL CHECK (ayin_gunu BETWEEN 1 AND 31),
    saat         time         NULL,
    baslangic    date         NOT NULL DEFAULT current_date,
    bitis        date         NULL,
    gizli        boolean      NOT NULL DEFAULT false,
    aktif        boolean      NOT NULL DEFAULT true,
    dosya_id     bigint       NULL REFERENCES dosya(id) ON DELETE SET NULL,
    olusturulma  timestamptz  NOT NULL DEFAULT now()
);

CREATE TABLE gorev (
    id              bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ust_gorev_id    bigint       NULL REFERENCES gorev(id) ON DELETE CASCADE,  -- alt iş
    baslik          varchar(300) NOT NULL,
    aciklama        text         NOT NULL DEFAULT '',
    tur             varchar(10)  NOT NULL DEFAULT 'is'
                    CHECK (tur IN ('is', 'durusma', 'kesif', 'haciz', 'rutin')),
    durum           varchar(12)  NOT NULL DEFAULT 'acik'
                    CHECK (durum IN ('acik', 'devam', 'onayda', 'tamamlandi', 'iptal')),
    onay_gerekir    boolean      NOT NULL DEFAULT false,
    oncelik         smallint     NOT NULL DEFAULT 1 CHECK (oncelik BETWEEN 0 AND 2),
    gizli           boolean      NOT NULL DEFAULT false,
    sorumlu_id      bigint       NULL REFERENCES kullanici(id) ON DELETE SET NULL,
    olusturan_id    bigint       NULL REFERENCES kullanici(id) ON DELETE SET NULL,
    son_tarih       date         NOT NULL,
    son_saat        time         NULL,  -- isteğe bağlı (B-9)
    bitis_saati     time         NULL,  -- duruşma/keşif bitişi
    yer             varchar(300) NOT NULL DEFAULT '',
    sonuc           varchar(10)  NOT NULL DEFAULT ''
                    CHECK (sonuc IN ('', 'olumlu', 'olumsuz', 'bekliyor')),
    sonuc_notu      text         NOT NULL DEFAULT '',
    -- Dosya bağı (icra şeması). Künye metinleri dosya satırı yokken de gösterim için tutulur.
    dosya_id        bigint       NULL REFERENCES dosya(id) ON DELETE SET NULL,
    taraf_id        bigint       NULL REFERENCES dosya_taraf(id) ON DELETE SET NULL,
    evrak_id        bigint       NULL REFERENCES evrak(id) ON DELETE SET NULL,
    tebligat_id     bigint       NULL REFERENCES tebligat_barkod(id) ON DELETE SET NULL,
    birim_adi       varchar(255) NOT NULL DEFAULT '',
    dosya_no        varchar(60)  NOT NULL DEFAULT '',
    dosya_turu      varchar(60)  NOT NULL DEFAULT '',
    taraf_adi       varchar(300) NOT NULL DEFAULT '',
    evrak_adi       varchar(500) NOT NULL DEFAULT '',
    barkod          varchar(32)  NOT NULL DEFAULT '',
    uyap_karti      jsonb        NULL,  -- "UYAP'ta aç" için kart bilgisi
    sablon_id       bigint       NULL REFERENCES sablon(id) ON DELETE SET NULL,
    surec_asama_id  bigint       NULL REFERENCES surec_asama(id) ON DELETE SET NULL,
    onceki_gorev_id bigint       NULL REFERENCES gorev(id) ON DELETE SET NULL,
    tekrar_id       bigint       NULL REFERENCES tekrar_kurali(id) ON DELETE SET NULL,
    durum_olayi_id  bigint       NULL REFERENCES durum_olayi(id) ON DELETE SET NULL,
    eski_id         bigint       NULL UNIQUE,  -- buluttaki zs_tasks kimliği (taşıma)
    sira            integer      NOT NULL DEFAULT 0,
    arama_metni     text         NOT NULL DEFAULT '',  -- Türkçe küçük harfe katlanmış (B-5)
    onaya_sunulma   timestamptz  NULL,
    tamamlanma      timestamptz  NULL,
    tamamlayan_id   bigint       NULL REFERENCES kullanici(id) ON DELETE SET NULL,
    olusturulma     timestamptz  NOT NULL DEFAULT now(),
    guncelleme      timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX gorev_sorumlu_tarih ON gorev (sorumlu_id, son_tarih) WHERE durum IN ('acik', 'devam', 'onayda');
CREATE INDEX gorev_tarih ON gorev (son_tarih);
CREATE INDEX gorev_dosya ON gorev (dosya_id);
CREATE INDEX gorev_ust ON gorev (ust_gorev_id);
CREATE INDEX gorev_dosya_no ON gorev (dosya_no);
-- Bir tekrar kuralının aynı anda yalnız bir açık örneği.
CREATE UNIQUE INDEX uq_gorev_tekrar_acik ON gorev (tekrar_id) WHERE tekrar_id IS NOT NULL AND durum IN ('acik', 'devam', 'onayda');

CREATE TABLE gorev_kisi (
    gorev_id     bigint      NOT NULL REFERENCES gorev(id) ON DELETE CASCADE,
    kullanici_id bigint      NOT NULL REFERENCES kullanici(id) ON DELETE CASCADE,
    rol          varchar(12) NOT NULL CHECK (rol IN ('sorumlu', 'onaylayici', 'izleyici')),
    ekleyen_id   bigint      NULL REFERENCES kullanici(id) ON DELETE SET NULL,
    olusturulma  timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (gorev_id, kullanici_id, rol)
);

CREATE TABLE gorev_etiket (
    gorev_id  bigint NOT NULL REFERENCES gorev(id) ON DELETE CASCADE,
    etiket_id bigint NOT NULL REFERENCES etiket(id) ON DELETE CASCADE,
    PRIMARY KEY (gorev_id, etiket_id)
);

CREATE TABLE gorev_not (
    id          bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gorev_id    bigint      NOT NULL REFERENCES gorev(id) ON DELETE CASCADE,
    yazan_id    bigint      NULL REFERENCES kullanici(id) ON DELETE SET NULL,
    metin       text        NOT NULL,
    olusturulma timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX gorev_not_gorev ON gorev_not (gorev_id);

-- Ek dosyalar ofis diskinde (%LOCALAPPDATA%\CokluUyap\ekler\<sha256>); bulut deposu yok.
CREATE TABLE gorev_ek (
    id          bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gorev_id    bigint       NOT NULL REFERENCES gorev(id) ON DELETE CASCADE,
    yukleyen_id bigint       NULL REFERENCES kullanici(id) ON DELETE SET NULL,
    ad          varchar(300) NOT NULL,
    mime        varchar(120) NOT NULL DEFAULT '',
    boyut       bigint       NOT NULL DEFAULT 0 CHECK (boyut >= 0),
    sha256      varchar(64)  NOT NULL,
    olusturulma timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX gorev_ek_gorev ON gorev_ek (gorev_id);

-- "Ertesi güne aktar" / ek süre. Onay gerektirmeyen işte doğrudan 'kabul' yazılır.
CREATE TABLE gorev_erteleme (
    id           bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gorev_id     bigint      NOT NULL REFERENCES gorev(id) ON DELETE CASCADE,
    isteyen_id   bigint      NULL REFERENCES kullanici(id) ON DELETE SET NULL,
    eski_tarih   date        NOT NULL,
    eski_saat    time        NULL,
    yeni_tarih   date        NOT NULL,
    yeni_saat    time        NULL,
    gerekce      text        NOT NULL DEFAULT '',
    durum        varchar(8)  NOT NULL DEFAULT 'bekliyor' CHECK (durum IN ('bekliyor', 'kabul', 'ret')),
    karar_veren_id bigint    NULL REFERENCES kullanici(id) ON DELETE SET NULL,
    karar_notu   text        NOT NULL DEFAULT '',
    karar_zamani timestamptz NULL,
    olusturulma  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX gorev_erteleme_gorev ON gorev_erteleme (gorev_id);
CREATE UNIQUE INDEX uq_gorev_erteleme_bekleyen ON gorev_erteleme (gorev_id) WHERE durum = 'bekliyor';

-- Geçmiş ve bildirim kaynağı. Tür listesi is_veri.rs'teki OlayTuru ile aynıdır.
CREATE TABLE gorev_olay (
    id          bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gorev_id    bigint      NULL REFERENCES gorev(id) ON DELETE CASCADE,
    kullanici_id bigint     NULL REFERENCES kullanici(id) ON DELETE SET NULL,
    tur         varchar(24) NOT NULL,
    ayrinti     jsonb       NOT NULL DEFAULT '{}',
    olusturulma timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX gorev_olay_gorev ON gorev_olay (gorev_id);

-- Kişinin bir işte gördüğü son olay (okunmamış rozeti).
CREATE TABLE gorev_goruldu (
    kullanici_id bigint NOT NULL REFERENCES kullanici(id) ON DELETE CASCADE,
    gorev_id     bigint NOT NULL REFERENCES gorev(id) ON DELETE CASCADE,
    son_olay_id  bigint NOT NULL DEFAULT 0,
    PRIMARY KEY (kullanici_id, gorev_id)
);

CREATE TABLE hatirlatici (
    id           bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gorev_id     bigint       NULL REFERENCES gorev(id) ON DELETE CASCADE,
    kullanici_id bigint       NOT NULL REFERENCES kullanici(id) ON DELETE CASCADE,
    olusturan_id bigint       NULL REFERENCES kullanici(id) ON DELETE SET NULL,
    zaman        timestamptz  NOT NULL,
    baslik       varchar(300) NOT NULL DEFAULT '',
    notu         text         NOT NULL DEFAULT '',
    gonderildi   timestamptz  NULL,
    olusturulma  timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX hatirlatici_bekleyen ON hatirlatici (zaman) WHERE gonderildi IS NULL;
