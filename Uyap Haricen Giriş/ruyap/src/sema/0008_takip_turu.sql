-- UYAP takip açılış ekranının seçenek ağacı: tür (kademe 1) → o türün yolları (2) → o yolun şekilleri (3).
-- Kodlar yalnız bu bağlamda anlamlıdır (şekil "0", İlamsız / Genel Haciz'de Örnek 7, İlamlı'da Örnek 4-5).
CREATE TABLE IF NOT EXISTS takip_turu_listesi (
    id bigint NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    kademe smallint NOT NULL CHECK (kademe BETWEEN 1 AND 3),
    takibin_turu varchar(8) NOT NULL,
    takibin_yolu varchar(8) NOT NULL DEFAULT '',
    takibin_sekli varchar(8) NOT NULL DEFAULT '',
    ad varchar(255) NOT NULL DEFAULT '',
    ornek_no varchar(10) NOT NULL DEFAULT '',
    guncelleme timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT uq_takip_turu_listesi UNIQUE (kademe, takibin_turu, takibin_yolu, takibin_sekli)
);
